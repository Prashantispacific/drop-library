import { z } from 'zod';

export const ItemCategoryEnum = z.enum([
  'reel',
  'article',
  'essay',
  'tool',
  'quote',
  'inspo',
]);

export const FlexibleCategorySchema = z.preprocess((val) => {
  if (typeof val !== 'string') return 'article';
  const s = val.toLowerCase().trim();
  if (s === 'reels' || s === 'reel' || s === 'video' || s === 'short' || s === 'shorts') return 'reel';
  if (s === 'articles' || s === 'article' || s === 'news' || s === 'web' || s === 'blog' || s === 'post') return 'article';
  if (s === 'essays' || s === 'essay') return 'essay';
  if (s === 'tools' || s === 'tool' || s === 'software' || s === 'app' || s === 'code') return 'tool';
  if (s === 'quotes' || s === 'quote') return 'quote';
  if (s === 'inspo' || s === 'inspiration' || s === 'idea' || s === 'design') return 'inspo';
  return 'article';
}, ItemCategoryEnum);

export const PlatformEnum = z.enum([
  'instagram',
  'youtube',
  'web',
  'text',
  'image',
]);

export const ItemStatusEnum = z.enum([
  'pending',
  'unfurling',
  'enriched',
  'failed',
]);

/**
 * Zod schema to validate structured outputs generated by AI models.
 * Ensures the response strictly adheres to the required contract with robust normalization.
 */
export const GeminiMetaSchema = z.object({
  title: z.preprocess((val) => (typeof val === 'string' && val.trim() ? val.trim() : 'Saved Drop'), z.string()),
  tldr: z.preprocess((val) => (typeof val === 'string' && val.trim() ? val.trim() : 'No summary generated'), z.string()),
  category: FlexibleCategorySchema,
  tags: z.preprocess((val) => {
    if (Array.isArray(val)) return val;
    if (typeof val === 'string') return val.split(/[,\s]+/).filter(Boolean);
    return ['vault'];
  }, z.array(z.string()).min(1).max(10).transform((tags) =>
    tags.map((t) => t.toLowerCase().trim().replace(/^#/, ''))
  )),
  searchSynonyms: z.preprocess((val) => {
    if (Array.isArray(val)) return val;
    if (typeof val === 'string') return val.split(/[,\s]+/).filter(Boolean);
    return [];
  }, z.array(z.string()).default([])),
  authorOrHandle: z.string().optional(),
  estimatedReadMinutes: z.number().int().nonnegative().optional(),
});

export const LibraryItemSchema = z.object({
  id: z.string(),
  schemaVersion: z.literal(1),
  createdAt: z.number(),
  updatedAt: z.number(),
  status: ItemStatusEnum,
  retryCount: z.number().nonnegative(),
  errorMessage: z.string().optional(),
  url: z.string().optional(),
  platform: PlatformEnum,
  rawShareText: z.string().optional(),
  quickNote: z.string().optional(),
  thumbnailUrl: z.string().optional(),
  noteContent: z.string().optional(),
  isMarkdown: z.boolean().optional(),
  meta: GeminiMetaSchema.optional(),
});

export const UserSettingsSchema = z.object({
  aiProvider: z.enum(['gemini', 'custom']).default('gemini'),
  geminiApiKey: z.string().default(''),
  geminiModel: z.string().default('gemini-3.5-flash-lite'),
  geminiBaseUrl: z.string().default(''),
  savedGeminiModels: z.array(z.string()).default([]),
  customApiUrl: z.string().default(''),
  customApiKey: z.string().default(''),
  customModel: z.string().default(''),
  savedCustomModels: z.array(z.string()).default([]),
  unfurlEndpoint: z.string().default(''),
  themeMode: z.enum(['oled', 'true-black']).default('oled'),
  autoEnrich: z.boolean().default(true),
  hapticFeedback: z.boolean().default(true),
  autoReturnAfterShare: z.boolean().default(true),
  returnDelaySeconds: z.number().min(0).max(5).default(0),
});

export type GeminiMetaValidated = z.infer<typeof GeminiMetaSchema>;
export type LibraryItemValidated = z.infer<typeof LibraryItemSchema>;
